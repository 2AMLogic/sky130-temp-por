def case_id(point: str, variant: str, rate: float) -> str:
    return f"{point}__{variant}__{sim_common.rate_tag(rate)}"


def build_matrix(man: dict) -> list[dict]:
    d = man["reassert_diagnosis"]
    cases = []
    for pname, pt in d["points"].items():
        for vname in d["solver_variants_at_exact_rate"]:
            cases.append({"point": pname, "variant": vname, "rate": pt["rate_v_per_s"], "role": "exact" if vname == "base" else "solver"})
        for rate in pt["adjacent_rates_v_per_s"]:
            for vname in d["adjacent_rate_variants"]:
                cases.append({"point": pname, "variant": vname, "rate": rate, "role": "adjacent-rate"})
    for c in cases:
        c["id"] = case_id(c["point"], c["variant"], c["rate"])
    ids = [c["id"] for c in cases]
    assert len(ids) == len(set(ids)), "duplicate matrix case"
    return cases


def netlist_for(head: str, man: dict, case: dict) -> str:
    d = man["reassert_diagnosis"]
    v = d["variants"][case["variant"]]
    base = camp.build_netlist(head, {"netlist_edit": None}, case["rate"])
    marker = "\n* temp_por_top -- generated by design/netlist.py"
    if base.count(marker) != 1:
        raise SystemExit("cannot locate the DUT splice point in the generated netlist")
    pre, post = base.split(marker)
    extra = ["", f"* ---- issue #142 diagnostic additions (case {case['id']}); circuit untouched ----",
             ".save " + " ".join(EXTRA_SAVES[:7]), ".save " + " ".join(EXTRA_SAVES[7:])]
    if v.get("options"):
        extra.append(f".options {v['options']}")
    return pre + "\n".join(extra) + "\n" + marker + post


def request_for(man: dict, case: dict, backend: str = "batch") -> dict:
    d = man["reassert_diagnosis"]
    pt = d["points"][case["point"]]
    v = d["variants"][case["variant"]]
    req = camp.build_request("netlist.spice", case["rate"], man, backend)
    req["corners"] = {"process": [pt["process"]], "supply_v": {"vset": [pt["supply_v"]]}, "temperature_c": [pt["temperature_c"]]}
    tstop = camp.tstop_for(case["rate"])
    tmax = v.get("tmax_s", camp.TMAX_S)
    req["analysis"] = {"kind": "tran", "args": f"1u {tstop:.9g} 0 {tmax:.3g}"}
    req["options"]["timeout_s"] = 2400
    return req


