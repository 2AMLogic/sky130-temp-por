"""Focused diagnosis of the two RESETn re-assertions in the as-drawn supply-ramp campaign (issue #142).

Source campaign: record 20261010-015905-fbd6329 (issue #101), where exactly two of 360 points released
RESETn once and then re-asserted it:

    A  ss, -40 C, 3.63 V, 500 kV/s        B  fs, 27 C, 2.97 V, 5 kV/s

Question: are these design-level behaviour of the RESETn -> temp_core.EN -> shared IBIAS -> POR_RAW loop,
or an artifact of the simulator landing on the nonphysical temp_core branch (issue #86)?

The matrix is declared in experiment.json (``reassert_diagnosis``).  Every case is ONE single-corner
``klt sim --backend batch`` request on the UNCHANGED assembled netlist (same testbench, same
design/netlist/temp_por_top.spice, nothing replaced by an ideal source).  The only deck additions are
extra ``.save`` cards (internal nodes for event ordering) and, for solver discriminators, a trailing
``.options`` card / a different ``tmax``.  This script never launches ngspice over the matrix and never
falls back to local runs: a refused / failed case is a recorded outcome.

Stages:  matrix | run | record
"""

