def first_violation(w, vf):
    """Per saved node: time of the first sample (t>0) outside [PHYS_LO, vf+PHYS_HI_MARGIN]."""
    hi = vf + rc.PHYS_HI_MARGIN
    t = w["time"]
    out = {}
    for name in rc.PHYS_NODES + tuple(EXTRA_SAVES):
        col = w.get(name)
        if col is None:
            continue
        for tt, x in zip(t, col):
            if tt > 0 and not (rc.PHYS_LO <= x <= hi):
                out[name] = {"t_s": tt, "v": x}
                break
    return out


def timeline(w, vf, res, window=200e-6):
    """Event order around each RESETn transition from the full-resolution trace (no inference)."""
    t = w["time"]
    v_mid = rc.FRAC_MID * vf
    rst = w["v(resetn)"]
    rel, fall = rc.schmitt(t, rst, rc.FRAC_IL * vf, rc.FRAC_IH * vf)
    ev = []
    for node in TIMELINE_NODES:
        col = w.get(node)
        if col is None:
            continue
        for d in ("rise", "fall"):
            for tc in rc.crossings(t, col, v_mid, d):
                ev.append({"t_s": tc, "node": node, "event": f"V_MID {d}"})
    viol_all = first_violation(w, vf)
    for node, vv in viol_all.items():
        ev.append({"t_s": vv["t_s"], "node": node, "event": f"FIRST out-of-window sample ({vv['v']:.3g} V)"})
    for tc in rel:
        ev.append({"t_s": tc, "node": "v(resetn)", "event": "RELEASE (V_IH rise)"})
    for tc in fall:
        ev.append({"t_s": tc, "node": "v(resetn)", "event": "RE-ASSERT (V_IL fall)"})
    ev.sort(key=lambda e: e["t_s"])
    out = {"anchors": [], "viol": viol_all}
    anchors = [("release", x) for x in rel] + [("reassert", x) for x in fall]
    for kind, ta in sorted(anchors, key=lambda a: a[1]):
        win = [e for e in ev if ta - window <= e["t_s"] <= ta + window]
        out["anchors"].append({
            "kind": kind, "t_s": ta,
            "ibias_v": {off: rc.interp_at(t, w["v(xdut.ibias)"], ta + off) for off in (-200e-6, -20e-6, 0.0, 20e-6, 200e-6)},
            "events_pm_200us": win,
        })
    # supply-current sign change (physicality onset by current) and PTAT/CTAT excursion onset are in 'viol'
    isup = [-x for x in w["i(bvdd)"]]
    first_neg = next((tt for tt, x in zip(t, isup) if tt > 0 and x < 0), None)
    out["first_negative_isup_s"] = first_neg
    return out


TRIGGER_COLS = ("v(vdd)", "v(resetn)", "v(xdut.por_raw)", "v(xdut.ibias)", "v(ptat)", "v(ctat)")
WINDOW_S = 100e-6  # every sample within +-WINDOW_S of a RESETn release/re-assert is kept (all columns)


def compress_ext(w, vf):
    names = [c for c in TRACE_COLS if c in w]
    cols = [w[c] for c in names]
    t = w["time"]
    n = len(t)
    rel, fall = rc.schmitt(t, w["v(resetn)"], rc.FRAC_IL * vf, rc.FRAC_IH * vf)
    anchors = rel + fall
    trig = [names.index(c) for c in TRIGGER_COLS if c in names]
    rows = [[c[0] for c in cols]]
    last = rows[0]
    for i in range(1, n - 1):
        cur = [c[i] for c in cols]
        in_win = any(abs(t[i] - a) <= WINDOW_S for a in anchors)
        if in_win or cur[0] - last[0] >= TRACE_DT or any(abs(cur[k] - last[k]) >= TRACE_DV for k in trig):
            rows.append(cur)
            last = cur
    rows.append([c[n - 1] for c in cols])
    return names, rows


def write_ext_trace(path, names, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# {','.join(names)}  (change-triggered: dV>={TRACE_DV * 1e3:g} mV on vdd/resetn/por_raw/ibias/ptat/ctat or dt>={TRACE_DT * 1e3:g} ms; every sample within +-100 us of a RESETn release/re-assert is kept)"]
    lines += [",".join(f"{x:.6g}" for x in r) for r in rows]
    with gzip.open(path, "wt", compresslevel=9) as fh:
        fh.write("\n".join(lines) + "\n")


def classify(res):
    """Per-run flags used by the verdict rules."""
    if res is None or "resetn" not in res:
        return {"usable": False}
    rs = res["resetn"]
    return {
        "usable": True,
        "physical": res["physical"]["ok"],
        "resolved": res["resolution_ok"] and res["ramp_ok"],
        "reasserts": rs["n_reassert"] > 0 or rs["n_release"] > 1 or rs["n_runt"] > 0,
        "n_release": rs["n_release"],
        "n_reassert": rs["n_reassert"],
        "t_release_s": rs["t_release_s"],
    }


def verdict_for_point(runs):
    """Strict rules from issue #142.

    design-level  : re-assertion (or repeated release / runt) on a run that is physical AND resolved.
    artifact      : at least one run exhibits the re-assertion on a NONphysical branch, AND at least
                    two physical+resolved runs at the exact rate (different solver settings) show a
                    single clean release with release times within REL_SPREAD_TOL of each other, AND
                    no physical+resolved run anywhere in this point's matrix (adjacent-rate
                    controls included) re-asserts.
    unresolved    : anything else.
    """
    flags = {r["id"]: classify(r.get("check")) for r in runs}
    good = [r for r in runs if flags[r["id"]].get("usable") and flags[r["id"]]["physical"] and flags[r["id"]]["resolved"]]
    design = [r["id"] for r in good if flags[r["id"]]["reasserts"]]
    if design:
        return "physical design-level re-assertion", f"re-assertion on physical, resolved run(s): {', '.join(design)}", flags
    exhibits = [r["id"] for r in runs if flags[r["id"]].get("usable") and flags[r["id"]]["reasserts"] and not flags[r["id"]]["physical"]]
    exact_good = [r for r in good if r["role"] in ("exact", "solver") and flags[r["id"]]["n_release"] == 1 and flags[r["id"]]["n_reassert"] == 0]
    if not exhibits:
        return "unresolved", "no run in this matrix reproduced the re-assertion (not even the original case), so there is no re-assertion whose disappearance could be shown", flags
    if len(exact_good) < 2:
        return "unresolved", f"re-assertion exhibited on a nonphysical branch ({', '.join(exhibits)}) but fewer than two physical+resolved single-release runs at the exact rate ({len(exact_good)}), so physical-branch stability is not demonstrated", flags
    tr = [flags[r["id"]]["t_release_s"] for r in exact_good]
    spread = (max(tr) - min(tr)) / (sum(tr) / len(tr))
    if spread > REL_SPREAD_TOL:
        return "unresolved", f"physical-branch release times disagree by {spread:.1%} (> {REL_SPREAD_TOL:.0%}) across {', '.join(r['id'] for r in exact_good)}", flags
    return "solver/nonphysical artifact", (
        f"re-assertion exhibited only on nonphysical run(s) {', '.join(exhibits)}; {len(exact_good)} physical+resolved exact-rate runs "
        f"({', '.join(r['id'] for r in exact_good)}) show one clean release with release-time spread {spread:.2%}; "
        "no physical+resolved run in the matrix re-asserts"), flags


def load_case(case, run_dir, man, corners_dir, write):
    d = run_dir / case["id"]
    rec = dict(case)
    rec.update({"tstop_s": camp.tstop_for(case["rate"])})
    rp = d / "report.json"
    attempts = []
    for ad in sorted(d.glob("attempt*")):
        try:
            body = json.loads((ad / "report.json").read_text()) if (ad / "report.json").is_file() else {}
            msg = (body.get("error") or {}).get("message") or ("report status " + str(body.get("status")))
        except json.JSONDecodeError:
            msg = "unparseable report"
        attempts.append(camp.scrub(msg, run_dir)[:400])
    if attempts:
        rec["failed_earlier_attempts"] = attempts
    if not rp.is_file():
        rec["outcome"] = "NOT SUBMITTED"
        rec["check"] = None
        return rec
    try:
        rep = json.loads(rp.read_text())
    except json.JSONDecodeError:
        rec["outcome"] = "NO JSON from klt: " + camp.scrub((d / "klt.stderr").read_text()[-500:], run_dir)
        rec["check"] = None
        return rec
    if "corners" not in rep:
        rec["outcome"] = "klt error (no corners reported): " + camp.scrub(str((rep.get("error") or {}).get("message", rep))[:500], run_dir)
        rec["check"] = None
        return rec
    remote = (rep.get("environment") or {}).get("remote") or {}
    rec.update({"job_id": remote.get("job_id"), "state": remote.get("state"), "instance_type": remote.get("instance_type"),
                "lifecycle": remote.get("lifecycle"), "runner_klt_version": remote.get("runner_klt_version"),
                "elapsed_seconds": remote.get("elapsed_seconds"), "klt_status": rep.get("status")})
    pt = man["reassert_diagnosis"]["points"][case["point"]]
    vf = pt["supply_v"]
    c = (rep.get("corners") or [None])[0]
    rec["diagnostics"] = [{"severity": g.get("severity"), "code": g.get("code"), "message": camp.scrub(g.get("message", ""), run_dir)[:300]} for g in (c or {}).get("diagnostics", [])]
    rec["runtime_s"] = (c or {}).get("runtime_s")
    art = (c or {}).get("artifacts") or {}
    wp = Path(art["waveform"]) if art.get("waveform") else None
    if wp is None or not wp.is_file():
        rec["outcome"] = "ERROR (no waveform retrieved)"
        rec["check"] = None
        return rec
    w = rc.load_wave(wp)
    res = rc.analyze(w, vf, case["rate"])
    rec["check"] = res
    rec["outcome"] = res["verdict"]
    if "resetn" in res:
        rows = rc.compress(w)
        st = rc.transitions_from_stored(rows, vf)
        res["stored_trace"] = {
            "rows": len(rows), "full_samples": len(w["time"]), "n_release": st["n_release"], "n_reassert": st["n_reassert"],
            "n_runt": st["n_runt"], "premature": st["premature"],
            "agrees_with_full_resolution": (st["n_release"] == res["resetn"]["n_release"] and st["n_reassert"] == res["resetn"]["n_reassert"]
                                            and st["n_runt"] == res["resetn"]["n_runt"] and st["premature"] == res["resetn"]["premature"]),
        }
        rec["timeline"] = timeline(w, vf, res)
        rec["missing_extra_saves"] = [n for n in EXTRA_SAVES if n not in w]
        if write:
            names, erows = compress_ext(w, vf)
            write_ext_trace(corners_dir / f"{case['id']}.trace.csv.gz", names, erows)
            rec["trace_file"] = f"{case['id']}.trace.csv.gz"
            rec["trace_rows"] = len(erows)
            art_log = Path(art["log"]).read_text() if art.get("log") and Path(art["log"]).is_file() else "(no log)"
            (corners_dir / f"{case['id']}.log").write_text(camp.scrub(art_log, run_dir))
    return rec


