def cmd_matrix(args) -> int:
    man = sim_common.load_manifest(MANIFEST)
    for c in build_matrix(man):
        print(f"{c['id']:40s} {c['role']:14s} rate={c['rate']:g}")
    return 0


def submit_case(case, head, man, run_dir):
    d = run_dir / case["id"]
    netlist = netlist_for(head, man, case)
    req = request_for(man, case)
    d.mkdir(parents=True, exist_ok=True)
    if (d / "report.json").is_file():
        n = 1
        while (d / f"attempt{n}").exists():
            n += 1
        (d / f"attempt{n}").mkdir()
        for name in ("report.json", "klt.stderr"):
            if (d / name).is_file():
                shutil.move(str(d / name), str(d / f"attempt{n}" / name))
    (d / "netlist.spice").write_text(netlist)
    (d / "request.json").write_text(json.dumps(req, indent=2) + "\n")
    say(f"[submit] {case['id']} -> batch fleet")
    p = subprocess.run(["klt", "sim", str(d / "request.json"), "--backend", "batch", "-o", str(d / "out"), "--format", "json"],
                       capture_output=True, text=True, timeout=4 * 3600)
    (d / "report.json").write_text(p.stdout)
    (d / "klt.stderr").write_text(p.stderr)
    try:
        st = json.loads(p.stdout).get("status", "?")
    except json.JSONDecodeError:
        st = "NO-JSON"
    say(f"[done]   {case['id']}: exit {p.returncode}, status {st}")
    return {"case": case["id"], "exit": p.returncode, "status": st}


def cmd_run(args) -> int:
    man = sim_common.load_manifest(MANIFEST)
    pdk = cr.resolve_pdk(cr.load_pin())
    git_info = cr.git_state()
    if git_info["dirty"] and not args.allow_dirty:
        raise SystemExit("working tree is dirty: commit (and push) first so the fleet source SHA resolves")
    now = datetime.now(timezone.utc)
    run_id = args.run_id or f"{now:%Y%m%d-%H%M%S}-{git_info['sha']}"
    run_dir = BUILD / run_id
    retry = args.retry_failed
    if retry:
        if not run_dir.exists():
            raise SystemExit(f"{run_dir} does not exist")
    else:
        if run_dir.exists():
            raise SystemExit(f"{run_dir} exists")
        run_dir.mkdir(parents=True)
    head = camp.tb_netlist_head(run_dir / ("retry" if retry else "."), pdk)
    cases = build_matrix(man)
    if args.only:
        cases = [c for c in cases if c["id"] in args.only]
    if retry:
        cases = [c for c in cases if not sim_common.report_usable(run_dir / c["id"] / "report.json")]
        say(f"retrying {len(cases)} case(s) without a usable report")
    meta = {"run_id": run_id, "started_utc": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "git": git_info,
            "klt_client": sim_common.klt_version(), "klt_sim_backend_env": os.environ.get("KLT_SIM_BACKEND"),
            "cases": [c["id"] for c in cases]}
    mp = run_dir / "run.json"
    if retry:
        old = json.loads(mp.read_text())
        old.setdefault("retries", []).append({"at_utc": meta["started_utc"], "git": git_info, "cases": meta["cases"]})
        meta = old
    else:
        mp.write_text(json.dumps(meta, indent=2) + "\n")
    results = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=min(2, args.jobs)) as ex:
        futs = [ex.submit(submit_case, c, head, man, run_dir) for c in cases]
        for c, f in zip(cases, futs):
            try:
                results.append(f.result())
            except Exception as err:  # noqa: BLE001 -- recorded
                results.append({"case": c["id"], "error": repr(err)})
                say(f"[error] {c['id']}: {err!r}")
    key = "retry_results" if retry else "submit_results"
    meta.setdefault(key, [])
    meta[key] = (meta[key] + results) if retry else results
    mp.write_text(json.dumps(meta, indent=2) + "\n")
    print(f"raw outputs: {run_dir}")
    return 0


