#!/usr/bin/env python3
"""Driver for the assembled temp_por_top supply-ramp campaign (issue #98).

The rate x process x temperature x supply grid is expressed as ``klt sim``
requests (one request per ramp rate: process x supply x temperature are klt's
own corner axes) and goes to the Spot batch fleet; this script never launches
ngspice over the grid itself.  The ramp-rate axis stays local to this
experiment: it is a ``.param rate`` written into one generated netlist per
request, not an extension of sim/bin/corner-run.py.

Stages (each is a subcommand):

  run        build netlists + requests, submit them to the fleet (explicit
             ``--backend batch``), keep the raw outputs under sim/build/.
  crosscheck one single-corner LOCAL probe (``--backend local``) compared with
             the fleet's result for the same point.
  record     grade every retrieved waveform with ramp_checker.py and write the
             append-only evidence: netlist snapshots, per-point logs, event-
             preserving traces, markdown + JSON record twins.
  selftest   run the transition checker on controlled waveforms (including a
             deliberate double release) and write a self-test record.

A batch submit failure is reported in the record; there is no local fallback.
"""

