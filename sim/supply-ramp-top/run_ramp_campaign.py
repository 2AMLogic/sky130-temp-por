def tb_netlist_head(run_dir: Path, pdk) -> str:
    """Netlist the testbench schematic with xschem; keep only the testbench part.

    The DUT subcircuits come from the committed design/netlist/temp_por_top.spice
    export (xschem 3.4.4 on this host leaves ``expr()`` device-parameter forms
    that ngspice cannot evaluate; the committed export was produced by 3.4.7).
    """
    out_dir = run_dir / "tb"
    produced = cr.netlist_with_xschem(TB_SCH, out_dir, pdk)
    text = produced.read_text().replace(str(REPO_ROOT) + os.sep, "")
    head = text.split("\n* expanding")[0]
    return "\n".join(ln for ln in head.splitlines() if ln.strip().lower() != ".end") + "\n"


def build_netlist(head: str, variant: dict, rate: float) -> str:
    dut = DUT_NETLIST.read_text()
    dut = "\n".join(ln for ln in dut.splitlines() if ln.strip().lower() != ".end") + "\n"
    edit = variant.get("netlist_edit")
    if edit:
        if dut.count(edit["find"]) != 1:
            raise SystemExit(f"variant edit target not found exactly once: {edit['find']!r}")
        dut = dut.replace(edit["find"], edit["replace"])
    banner = (
        f"* {SLUG}: generated by sim/supply-ramp-top/run_ramp_campaign.py -- do not edit\n"
        f"* ramp rate (V/s): {rate:g}   variant edit: {'none' if not edit else edit['find'] + ' -> ' + edit['replace']}\n"
        f".param rate={rate:g}\n"
        "* ng_nomodcheck: same setting as sim/spiceinit; carried in the netlist because the\n"
        "* fleet runner ignores options.ngspice_init (see experiment.json ngspice_note)\n"
        ".control\nset ng_nomodcheck\n.endc\n"
    )
    return banner + head + "\n" + dut


def build_request(netlist_name: str, rate: float, man: dict, backend: str, capacity_wait_s: float = 0) -> dict:
    tstop = tstop_for(rate)
    t_at = f"{(tstop - 0.1e-3):.9g}"
    c = man["corners"]
    req = {
        "netlist": netlist_name,
        "backend": backend,
        "models": {"pdk": "sky130A", "lib": MODEL_LIB},
        "corners": {
            "process": c["process"],
            "supply_v": {"vset": c["supply_v"]},
            "temperature_c": c["temperature_c"],
        },
        "analysis": {"kind": "tran", "args": f"1u {tstop:.9g} 0 {TMAX_S:.3g}"},
        "measurements": [
            {"name": "vdd_end", "spice": f".meas tran vdd_end FIND v(vdd) AT={t_at}", "unit": "V"},
            {"name": "resetn_end", "spice": f".meas tran resetn_end FIND v(resetn) AT={t_at}", "unit": "V"},
            {"name": "resetn_max", "spice": ".meas tran resetn_max MAX v(resetn)", "unit": "V"},
            {"name": "por_raw_max", "spice": ".meas tran por_raw_max MAX v(xdut.por_raw)", "unit": "V"},
            {"name": "ibias_end", "spice": f".meas tran ibias_end FIND v(xdut.ibias) AT={t_at}", "unit": "V"},
        ],
        "options": {"timeout_s": 1500, "keep_artifacts": True, "waveforms": True},
    }
    if backend == "batch":
        req["batch"] = {"runner_version_check": "warn"}
        if capacity_wait_s:
            req["batch"]["capacity_wait_s"] = capacity_wait_s
    return req


def klt_version() -> str:
    p = subprocess.run(["klt", "--version"], capture_output=True, text=True)
    return p.stdout.strip() or p.stderr.strip()


def submit(variant_name: str, rate: float, head: str, man: dict, run_dir: Path, capacity_wait_s: float = 0) -> dict:
    tag = rate_tag(rate)
    d = run_dir / variant_name / tag
    d.mkdir(parents=True, exist_ok=True)
    # a previous attempt that never produced a usable report is archived, not overwritten
    prev = d / "report.json"
    if prev.is_file():
        n = 1
        while (d / f"attempt{n}").exists():
            n += 1
        arch = d / f"attempt{n}"
        arch.mkdir()
        for name in ("report.json", "klt.stderr"):
            if (d / name).is_file():
                shutil.move(str(d / name), str(arch / name))
    netlist = d / "netlist.spice"
    netlist.write_text(build_netlist(head, man["variants"][variant_name], rate))
    req = build_request("netlist.spice", rate, man, "batch", capacity_wait_s)
    (d / "request.json").write_text(json.dumps(req, indent=2) + "\n")
    cmd = ["klt", "sim", str(d / "request.json"), "--backend", "batch", "-o", str(d / "out"), "--format", "json"]
    say(f"[submit] {variant_name} {tag}: {len(man['corners']['process']) * 9} points -> batch fleet")
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=4 * 3600)
    (d / "report.json").write_text(p.stdout)
    (d / "klt.stderr").write_text(p.stderr)
    status = "?"
    try:
        status = json.loads(p.stdout).get("status", "?")
    except json.JSONDecodeError:
        status = "NO-JSON"
    say(f"[done]   {variant_name} {tag}: exit {p.returncode}, report status {status}")
    return {"variant": variant_name, "rate": rate, "tag": tag, "exit": p.returncode, "status": status}


def cmd_run(args) -> int:
    man = load_manifest()
    pdk = cr.resolve_pdk(cr.load_pin())
    git_info = cr.git_state()
    now = datetime.now(timezone.utc)
    run_id = args.run_id or f"{now:%Y%m%d-%H%M%S}-{git_info['sha']}"
    run_dir = BUILD / run_id
    if args.retry_failed:
        if not run_dir.exists():
            raise SystemExit(f"{run_dir} does not exist")
    else:
        if run_dir.exists():
            raise SystemExit(f"{run_dir} exists; refusing to reuse a run id")
        run_dir.mkdir(parents=True)
    head = tb_netlist_head(run_dir, pdk) if not args.retry_failed else tb_netlist_head(run_dir / "retry", pdk)
    variants = args.variant or list(man["variants"])
    work = [(v, r) for v in variants for r, _ in all_rates(man)]
    if args.retry_failed:
        def usable(v, r):
            rp = run_dir / v / rate_tag(r) / "report.json"
            if not rp.is_file():
                return False
            try:
                return "corners" in json.loads(rp.read_text())
            except json.JSONDecodeError:
                return False
        work = [(v, r) for v, r in work if not usable(v, r)]
        say(f"retrying {len(work)} request(s) without a usable report, capacity_wait_s={args.capacity_wait}")
    meta = {
        "run_id": run_id,
        "started_utc": now.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "variants": variants,
        "klt_client": klt_version(),
        "klt_sim_backend_env": os.environ.get("KLT_SIM_BACKEND"),
        "work": [[v, r] for v, r in work],
    }
    if not args.retry_failed:
        (run_dir / "run.json").write_text(json.dumps(meta, indent=2) + "\n")
    say(f"run id {run_id}: {len(work)} requests ({len(variants)} variant(s) x {len(work) // len(variants)} rates)")
    results = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=min(2, args.jobs)) as ex:
        futs = [ex.submit(submit, v, r, head, man, run_dir, args.capacity_wait) for v, r in work]
        for f in futs:
            try:
                results.append(f.result())
            except Exception as err:  # noqa: BLE001 -- recorded, never swallowed
                results.append({"error": repr(err)})
                say(f"[error] submit raised: {err!r}")
    meta["submit_results" if not args.retry_failed else "retry_results"] = results
    if args.retry_failed:
        old = json.loads((run_dir / "run.json").read_text())
        old.setdefault("retries", []).append({"at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "capacity_wait_s": args.capacity_wait, "results": results})
        meta = old
    (run_dir / "run.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"raw outputs: {run_dir}")
    return 0


