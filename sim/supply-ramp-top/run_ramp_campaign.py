HERE = Path(__file__).resolve().parent
SIM_DIR = HERE.parent
REPO_ROOT = SIM_DIR.parent
sys.path.insert(0, str(SIM_DIR / "bin"))
sys.path.insert(0, str(HERE))

import ramp_checker as rc  # noqa: E402
import sim_common  # noqa: E402

cr = sim_common.load_corner_run()

SLUG = "supply-ramp-top"
MANIFEST = HERE / "experiment.json"
TB_SCH = HERE / "testbench" / "tb_temp_por_ramp.sch"
DUT_NETLIST = REPO_ROOT / "design" / "netlist" / "temp_por_top.spice"
BUILD = REPO_ROOT / "sim" / "build" / SLUG
HOLD_S = 15e-3
RATE_CEIL_SUPPLY = 3.63
TMAX_S = 5e-6
MODEL_LIB = "libs.tech/combined/sky130.lib.spice"

_print_lock = threading.Lock()


def say(msg: str) -> None:
    with _print_lock:
        print(msg, flush=True)


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text())


def rate_tag(rate: float) -> str:
    return "r" + f"{rate:g}".replace("+", "")


def corner_id(proc: str, temp: float, vf: float) -> str:
    return f"{proc}_{cr.fmt_temp(temp)}c_{vf:.2f}v"


def tstop_for(rate: float) -> float:
    return RATE_CEIL_SUPPLY / rate + HOLD_S


def all_rates(man: dict) -> list[tuple[float, float | None]]:
    """[(rate, primary_rate_or_None)] -- primaries first, each followed by its half-rate guard."""
    out = []
    factor = man["rates"]["half_rate_guard_factor"]
    for r in man["rates"]["primary_v_per_s"]:
        out.append((r, None))
        out.append((r * factor, r))
    return out


