def scrub(text: str, run_dir: Path) -> str:
    text = text.replace(str(run_dir), "<build>")
    text = text.replace(str(REPO_ROOT) + os.sep, "")
    return re.sub(r"/home/[^/\s]+", "<home>", text)


def point_log(corner: dict, d_out: Path, header: list[str], run_dir: Path) -> str:
    art = corner.get("artifacts") or {}
    deck = Path(art["deck"]).read_text() if art.get("deck") and Path(art["deck"]).is_file() else "(no deck retrieved)"
    log = Path(art["log"]).read_text() if art.get("log") and Path(art["log"]).is_file() else "(no ngspice log retrieved)"
    lines = list(header) + [""]
    lines += ["# ==== klt sim deck (exact input given to ngspice on the runner) ====", *[f"| {ln}" for ln in deck.splitlines()], ""]
    lines += ["# ==== klt diagnostics ====", *[f"| {dg.get('severity')}/{dg.get('code')}: {dg.get('message')}" for dg in corner.get("diagnostics", [])], ""]
    lines += ["# ==== ngspice stdout+stderr ====", log.rstrip(), ""]
    return scrub("\n".join(lines), run_dir)


def classify_error(corner: dict, log_text: str) -> str:
    if "could not find a valid modelname" in log_text:
        return "model_not_found (no valid model bin for a drawn device geometry)"
    codes = [d.get("code") for d in corner.get("diagnostics", [])]
    if any(c and "timeout" in c for c in codes):
        return "timeout"
    return "error:" + ",".join(sorted({c for c in codes if c})) if codes else "error"


def analyze_variant(variant: str, run_dir: Path, man: dict, corners_dir: Path, write: bool) -> dict:
    points, requests = [], []
    pdk_info = {}
    for rate, primary in all_rates(man):
        tag = rate_tag(rate)
        d = run_dir / variant / tag
        rep_path = d / "report.json"
        req_rec = {"rate_v_per_s": rate, "tag": tag, "primary_rate": primary, "tstop_s": tstop_for(rate)}
        attempts = []
        for ad in sorted(d.glob("attempt*")):
            try:
                body = json.loads((ad / "report.json").read_text()) if (ad / "report.json").is_file() else {}
                msg = (body.get("error") or {}).get("message") or ("report status " + str(body.get("status")))
            except json.JSONDecodeError:
                msg = "unparseable report"
            attempts.append(scrub(msg, run_dir)[:400])
        if attempts:
            req_rec["failed_earlier_attempts"] = attempts
        if not rep_path.is_file():
            req_rec["outcome"] = "NOT SUBMITTED / no report"
            requests.append(req_rec)
            continue
        try:
            rep = json.loads(rep_path.read_text())
        except json.JSONDecodeError:
            req_rec["outcome"] = "NO JSON (klt failed before a report existed): " + scrub((d / "klt.stderr").read_text()[-600:], run_dir)
            requests.append(req_rec)
            continue
        if "corners" not in rep:
            req_rec["outcome"] = "klt error (no corners reported): " + scrub(str((rep.get("error") or {}).get("message", rep))[:500], run_dir)
            requests.append(req_rec)
            continue
        remote = (rep.get("environment") or {}).get("remote") or {}
        req_rec.update(
            {
                "outcome": rep.get("status"),
                "job_id": remote.get("job_id"),
                "instance_type": remote.get("instance_type"),
                "lifecycle": remote.get("lifecycle"),
                "runner_klt_version": remote.get("runner_klt_version"),
                "client_klt_version": remote.get("client_klt_version"),
                "elapsed_seconds": remote.get("elapsed_seconds"),
                "state": remote.get("state"),
                "corner_count": rep.get("corner_count"),
            }
        )
        pdk_info = (rep.get("provenance") or {}).get("pdk", pdk_info)
        requests.append(req_rec)
        for c in rep.get("corners", []):
            proc = c["process"]
            vf = c["supply_v"]["vset"]
            temp = c["temperature_c"]
            cid = corner_id(proc, temp, vf)
            art = c.get("artifacts") or {}
            wave_path = Path(art["waveform"]) if art.get("waveform") else None
            log_text = Path(art["log"]).read_text() if art.get("log") and Path(art["log"]).is_file() else ""
            ngv = re.findall(r"(ngspice-\d+) done", log_text)
            pt = {
                "id": cid,
                "variant": variant,
                "rate_v_per_s": rate,
                "rate_tag": tag,
                "primary_rate": primary,
                "process": proc,
                "temperature_c": temp,
                "supply_v": vf,
                "klt_status": c.get("status"),
                "runtime_s": c.get("runtime_s"),
                "ngspice": ngv[0] if ngv else None,
                "measurements": {m["name"]: m.get("value") for m in c.get("measurements", [])},
                "diagnostics": [{"severity": dg.get("severity"), "code": dg.get("code"), "message": scrub(dg.get("message", ""), run_dir)[:400]} for dg in c.get("diagnostics", [])],
            }
            res = None
            if wave_path is not None and wave_path.is_file():
                wave = rc.load_wave(wave_path)
                res = rc.analyze(wave, vf, rate)
                if "resetn" in res:
                    rows = rc.compress(wave)
                    st = rc.transitions_from_stored(rows, vf)
                    res["stored_trace"] = {
                        "rows": len(rows),
                        "full_samples": len(wave["time"]),
                        "n_release": st["n_release"],
                        "n_reassert": st["n_reassert"],
                        "n_runt": st["n_runt"],
                        "premature": st["premature"],
                        "agrees_with_full_resolution": (
                            st["n_release"] == res["resetn"]["n_release"]
                            and st["n_reassert"] == res["resetn"]["n_reassert"]
                            and st["n_runt"] == res["resetn"]["n_runt"]
                            and st["premature"] == res["resetn"]["premature"]
                        ),
                    }
                    if write:
                        rc.write_trace(corners_dir / tag / f"{cid}.trace.csv.gz", rows)
            if res is None:
                pt["outcome"] = "ERROR"
                pt["error_class"] = classify_error(c, log_text)
                pt["check"] = None
            else:
                pt["outcome"] = res["verdict"]
                pt["check"] = res
            if write:
                header = [
                    f"# point: {SLUG} {variant} {tag} {cid}",
                    f"# process={proc} temp={cr.fmt_temp(temp)}C final_supply={vf:.2f}V rate={rate:g} V/s tstop={tstop_for(rate):.6g}s",
                    f"# klt status: {c.get('status')}   runtime on runner: {c.get('runtime_s')} s   outcome: {pt['outcome']}",
                ]
                (corners_dir / tag).mkdir(parents=True, exist_ok=True)
                (corners_dir / tag / f"{cid}.log").write_text(point_log(c, run_dir, header, run_dir))
            points.append(pt)
    return {"points": points, "requests": requests, "fleet_pdk_report": pdk_info}


def grade_pairs(points: list[dict], man: dict) -> list[dict]:
    q = man["grading"]["quasi_static"]
    lo, hi = q["release_delay_ratio_band"]
    tol = q["vdd_at_por_raw_rise_tolerance_v"]
    by = {(p["rate_v_per_s"], p["id"]): p for p in points}
    pairs = []
    for p in points:
        if p["primary_rate"] is not None:
            continue
        half = by.get((p["rate_v_per_s"] * man["rates"]["half_rate_guard_factor"], p["id"]))
        rec = {"id": p["id"], "rate_v_per_s": p["rate_v_per_s"], "half_rate_v_per_s": p["rate_v_per_s"] * man["rates"]["half_rate_guard_factor"]}
        a, b = p.get("check"), (half or {}).get("check")
        if not a or not b or "resetn" not in a or "resetn" not in b:
            rec.update(grade="n/a (a segment has no waveform)", por_raw_vdd_grade="n/a", delay_grade="n/a")
            pairs.append(rec)
            continue
        ra, rb = a["por_raw"], b["por_raw"]
        if ra["t_rise_mid_s"] is None or rb["t_rise_mid_s"] is None:
            rec["por_raw_vdd_grade"] = "n/a (POR_RAW never rose in a segment)"
        elif ra["rise_after_ramp_end_censored"] or rb["rise_after_ramp_end_censored"]:
            rec["por_raw_vdd_grade"] = "censored (POR_RAW rose after the ramp ended in a segment: no VDD threshold measured)"
            rec["vdd_at_rise_full_v"], rec["vdd_at_rise_half_v"] = ra["vdd_at_rise_v"], rb["vdd_at_rise_v"]
        elif not (ra["vdd_at_rise_resolved"] and rb["vdd_at_rise_resolved"]):
            rec["por_raw_vdd_grade"] = "unresolved (too few ramp samples to interpolate the crossing)"
            rec["vdd_at_rise_full_v"], rec["vdd_at_rise_half_v"] = ra["vdd_at_rise_v"], rb["vdd_at_rise_v"]
        else:
            dv = ra["vdd_at_rise_v"] - rb["vdd_at_rise_v"]
            rec["vdd_at_rise_full_v"], rec["vdd_at_rise_half_v"], rec["vdd_at_rise_delta_v"] = ra["vdd_at_rise_v"], rb["vdd_at_rise_v"], dv
            rec["por_raw_vdd_grade"] = "consistent" if abs(dv) <= tol else "rate-dependent"
        da, db = a["release_delay_s"], b["release_delay_s"]
        if da is None or db is None or db == 0:
            rec["delay_grade"] = "n/a (a segment has no release)"
        else:
            ratio = da / db
            rec["release_delay_full_s"], rec["release_delay_half_s"], rec["release_delay_ratio"] = da, db, ratio
            rec["delay_grade"] = "consistent" if lo <= ratio <= hi else "rate-dependent"
        rec["grade"] = rec["por_raw_vdd_grade"] if not rec["por_raw_vdd_grade"].startswith("consistent") else rec["delay_grade"]
        pairs.append(rec)
    return pairs


def summarize(points: list[dict]) -> dict:
    out: dict = {}
    for p in points:
        s = out.setdefault(p["rate_tag"], {"rate_v_per_s": p["rate_v_per_s"], "n": 0, "outcome": {}, "transition_verdict": {}, "fail_codes": {}, "nonphysical": 0})
        s["n"] += 1
        s["outcome"][p["outcome"]] = s["outcome"].get(p["outcome"], 0) + 1
        if p["outcome"] == "ERROR":
            k = p.get("error_class", "error")
            s["fail_codes"][k] = s["fail_codes"].get(k, 0) + 1
            continue
        chk = p["check"]
        if "transition_verdict" not in chk:
            continue
        s["transition_verdict"][chk["transition_verdict"]] = s["transition_verdict"].get(chk["transition_verdict"], 0) + 1
        for code in chk["fail_codes"]:
            s["fail_codes"][code] = s["fail_codes"].get(code, 0) + 1
        if not chk["physical"]["ok"]:
            s["nonphysical"] += 1
    return out


def fmt(x, spec=".4g", unit=""):
    return "n/a" if x is None else f"{x:{spec}}{unit}"


def render_md(rec: dict) -> str:
    L = [f"# Record {rec['record_id']}", ""]
    L += sim_common.render_record_id_experiment(rec["record_id"], rec["experiment"]["slug"], rec["experiment"]["title"])
