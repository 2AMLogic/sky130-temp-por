#!/usr/bin/env python3
"""Forced-offset early-BIAS_OK / POR_RAW-pulse experiment (issue #495).

A bespoke runner (not an `experiment.json` corner run): the swept axes are a forced
offset spliced into a derived `bias_core` copy, the solver start (default / uic / gmin)
and the ramp rate -- none of which a corner request can express.

Execution model: the whole grid is ONE `klt sim` deck-list request submitted to the Spot
batch fleet (host rules: never a hand-launched ngspice grid, never a local fallback when
the fleet refuses).  `--probe POINT_ID` runs ONE point locally for a debug cross-check.

    run_early_assert.py --grid pilot --wait-for-capacity 600
    run_early_assert.py --grid full  --wait-for-capacity 600
    run_early_assert.py --grid full --dry-run
    run_early_assert.py --probe ss_m40c_r100_uic_offp006
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM_DIR = HERE.parent
REPO_ROOT = SIM_DIR.parent
SLUG = "por-bias-ok-early-assert"
MANIFEST = HERE / "experiment.json"
TESTBENCH = HERE / "testbench" / "tb_bias_ok_early_assert.sch"
NETLIST_DIR = REPO_ROOT / "design" / "netlist"
BUILD_DIR = SIM_DIR / "build" / SLUG
sys.path.insert(0, str(SIM_DIR / "bin"))
sys.path.insert(0, str(HERE))
import evidence_store  # noqa: E402
import pulse_extractor  # noqa: E402
import sim_common  # noqa: E402

cr = sim_common.load_corner_run()

# device -> (original line prefix, replacement with a series VOFF source behind the device's gate)
OFFSETS = {
    "XMOL2": ("XMOL2 NOKO NOKL VSS VSS", "VOFF NOKLG NOKL DC {voff}\nXMOL2 NOKO NOKLG VSS VSS"),
    "XMOKA": ("XMOKA NOKO NA TOK VDD", "VOFF NAG NA DC {voff}\nXMOKA NOKO NAG TOK VDD"),
}
WAVE = "wave.dat"


@dataclass(frozen=True)
class Point:
    proc: str
    temp_c: float
    rate: float
    start: str
    offset_mv: int
    device: str = "XMOL2"

    @property
    def point_id(self) -> str:
        t = f"m{abs(int(self.temp_c))}c" if self.temp_c < 0 else f"{int(self.temp_c)}c"
        o = f"{'p' if self.offset_mv >= 0 else 'm'}{abs(self.offset_mv):03d}"
        return f"{self.proc}_{t}_r{self.rate:g}_{self.start}_{self.device.lower()}_off{o}"


def build_points(grid: str, man: dict) -> list[Point]:
    g = man["grids"][grid]
    pairs = [tuple(p) for p in g["paired"]] if "paired" in g else [(p, t) for p in g["process"] for t in g["temperature_c"]]
    offs = g["offset_mv"]  # {device: [mV, ...]}
    pts = [Point(p, t, r, s, o, d) for p, t in pairs for r in g["rate_v_per_s"] for s in g["starts"] for d, ol in offs.items() for o in ol]
    rs = g.get("rate_sweep")
    if rs:
        pts += [Point(p, t, r, s, o, d) for p, t in pairs for r in rs["rate_v_per_s"] for s in rs["starts"] for d, ol in offs.items() for o in ol]
    return pts


def derived_bias_core(device: str) -> str:
    old, new = OFFSETS[device]
    txt = (NETLIST_DIR / "bias_core.spice").read_text()
    if txt.count(old) != 1:
        raise cr.HarnessError(f"expected exactly one {old!r} in design/netlist/bias_core.spice")
    return sim_common.drop_end(txt.replace(old, new))


def build_body(head: str, device: str) -> str:
    dut = "".join(sim_common.drop_end((NETLIST_DIR / n).read_text()) for n in ("por_comparator.spice", "por_output_chain.spice"))
    return head + "\n" + dut + derived_bias_core(device)


def build_deck(pt: Point, bodies: dict) -> str:
    tstop = 2 * 3.63 / pt.rate
    tmax = 0.002 / pt.rate
    lines = [
        f"* {SLUG} point deck -- generated by sim/{SLUG}/run_early_assert.py",
        f"* point: {pt.point_id}",
        f".param rate={pt.rate:g}",
        f".param voff={pt.offset_mv * 1e-3:g}",
        f'.lib "{sim_common.runner_lib_ref()}" {pt.proc}',
        f".temp {pt.temp_c:g}",
    ]
    if pt.start == "gmin":
        lines.append(".options gmin=1e-11")
    lines.append(bodies[pt.device])
    uic = " uic" if pt.start == "uic" else ""
    lines += [
        ".control",
        "set ng_nomodcheck",
        "set wr_singlescale",
        "set wr_vecnames",
        "option numdgt=7",
        f"tran 1u {tstop:.9g} 0 {tmax:.6g}{uic}",
        f"wrdata {WAVE} v(vdd) v(por_raw) v(bias_ok) v(resetn) v(xbias.na)",
        "quit",
        ".endc",
        ".end",
        "",
    ]
    return "\n".join(lines)


def deck_unit(pt: Point, body: dict, timeout: int) -> tuple[dict, dict[str, str]]:
    base = f"units/{pt.point_id}"
    unit = {"id": pt.point_id, "deck": f"{base}/deck.spice", "inputs": [{"path": f"{base}/spiceinit", "name": ".spiceinit"}],
            "outputs": [WAVE], "timeout_s": timeout}
    files = {f"{base}/deck.spice": build_deck(pt, body), f"{base}/spiceinit": sim_common.spiceinit_text(SIM_DIR, by=f"{SLUG}/run_early_assert.py")}
    return unit, files


def build_request(points, body, pdk, backend, args):
    units, files = [], {}
    for pt in points:
        u, f = deck_unit(pt, body, args.timeout)
        units.append(u)
        files.update(f)
    req = sim_common.deck_request(units, backend, timeout_s=args.timeout, pdk_variant=pdk.variant,
                                  capacity_wait_s=args.wait_for_capacity if backend == "batch" else 0, max_workers=args.max_workers)
    return req, files


def unit_wave(out_dir: Path, pid: str) -> str | None:
    for cand in (out_dir / pid / WAVE, out_dir / "units" / pid / WAVE):
        if cand.is_file():
            return cand.read_text()
    hits = list(out_dir.rglob(f"{pid}/{WAVE}"))
    return hits[0].read_text() if hits else None


def grade(pt: Point, wave_text: str | None, settle_s: float) -> dict:
    if wave_text is None:
        return {"status": "no_data", "class": "no_data"}
    r = pulse_extractor.extract(pulse_extractor.load_wrdata(wave_text), settle_s=settle_s)
    r["class"] = pulse_extractor.verdict_class(r)
    return r


def run_probe(args, pdk, man) -> int:
    pts = {p.point_id: p for p in build_points("full", man) + build_points("pilot", man)}
    if args.probe not in pts:
        raise cr.HarnessError(f"no point {args.probe!r}; use --dry-run to list ids")
    pt = pts[args.probe]
    d = BUILD_DIR / "probe" / pt.point_id
    d.mkdir(parents=True, exist_ok=True)
    head = sim_common.netlist_tb_head(TESTBENCH, d / "tb", pdk)
    req, files = build_request([pt], {d: build_body(head, d) for d in OFFSETS}, pdk, "local", args)
    for rel, text in files.items():
        (d / rel).parent.mkdir(parents=True, exist_ok=True)
        (d / rel).write_text(text)
    (d / "request.json").write_text(json.dumps(req, indent=2) + "\n")
    print(f"[probe] local single point {pt.point_id} (debug only, nothing recorded)")
    proc = sim_common.run_local_probe(d)
    out = d / "out"
    res = grade(pt, unit_wave(out, pt.point_id), man["settle_s"] if "settle_s" in man else 2e-3)
    print(f"[probe] klt exit {proc.returncode}")
    print(json.dumps(res, indent=2, default=str))
    return 0 if proc.returncode == 0 else 1


def mv(x):
    return "-" if x is None else f"{x * 1e3:.1f}"


def vv(x):
    return "-" if x is None else f"{x:.4f}"


def render_md(rec: dict) -> str:
    L = [f"# {SLUG} -- {rec['record_id']}", "", f"- **Experiment**: `{SLUG}` -- {rec['experiment']['title']}",
         f"- **Grid**: `{rec['grid']}` ({len(rec['points'])} decks, one `klt sim` deck-list request, batch fleet)",
         f"- **Author**: {rec['author']}", f"- **Supersedes**: {rec['supersedes'] or 'none'}",
         f"- **PDK / tools**: {rec['pdk_line']}", f"- **Repo state**: {rec['git']['sha']}{' (dirty)' if rec['git'].get('dirty') else ''}", "",
         f"- **Subset reason**: {rec['matrix']['subset_reason']}", "",
         "## Verdict", "", rec["verdict"], "",
         "## Per-point results", "",
         "Offset (mV) is forced behind the gate of the device named in the point id (xmol2 = mirror output leg, xmoka = OK-detector input device on NA). BIAS_OK = VDD of first BIAS_OK assertion on the UP ramp; VPOR-up = genuine POR_RAW release; "
         "pulse = POR_RAW release-then-reassert before it (start VDD, width mV of VDD / us measured); RESETn = whether a pulse reached RESETn.", "",
         "| point | class | BIAS_OK (V) | VPOR-up (V) | pulses | pulse start (V) | width (mV) | width (us) | RESETn early (V) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for p in rec["points"]:
        g = p["grade"]
        pl = g.get("pulses") or []
        first = pl[0] if pl else None
        L.append(f"| `{p['point_id']}` | {g['class']} | {vv(g.get('bias_ok_up_v'))} | {vv(g.get('por_up_v'))} | {g.get('pulse_count', '-')} | "
                 f"{vv(first['v_start']) if first else '-'} | {mv(first['width_v']) if first else '-'} | "
                 f"{'%.0f' % (first['width_s'] * 1e6) if first else '-'} | {vv(g.get('resetn_early_v'))} |")
    L += ["", "Per-point waveforms and logs are in the artifact store; see the JSON twin for every extracted field.", ""]
    return "\n".join(L)


def verdict(points: list[dict]) -> str:
    cls = [p["grade"]["class"] for p in points]
    n = {c: cls.count(c) for c in sorted(set(cls))}
    ctrl = [p for p in points if p["offset_mv"] == 0]
    ctrl_bad = [p["point_id"] for p in ctrl if p["grade"]["class"] != "clean"]
    s = f"Point classes: {n}. "
    s += ("Zero-offset controls clean at every point. " if not ctrl_bad else f"Zero-offset controls NOT clean: {ctrl_bad}. ")
    if "pulse_propagates" in n:
        s += "VERDICT (c): at least one point is reachable AND propagates to RESETn."
    elif "pulse_absorbed" in n:
        s += "VERDICT (b): pulse reachable on the forced-offset axis but absorbed before RESETn at every point where it occurs."
    else:
        s += "VERDICT (a): no forced-offset point in this grid produced a POR_RAW release-then-reassert pulse."
    return s


def parse_args(argv):
    p = argparse.ArgumentParser(description="forced-offset early-BIAS_OK experiment (issue #495)")
    p.add_argument("--grid", choices=("pilot", "pilot-extended", "full"), default="pilot")
    p.add_argument("--probe", metavar="POINT_ID", help="run ONE point locally (debug, nothing recorded)")
    p.add_argument("--max-workers", type=int, default=8)
    p.add_argument("--subset-reason", default="")
    sim_common.add_common_args(p, timeout_default=900)
    return p.parse_args(argv)


def main(argv) -> int:
    args = parse_args(argv)
    man = json.loads(MANIFEST.read_text())
    if not (args.dry_run or args.probe):
        evidence_store.preflight_or_exit()
    pin = cr.load_pin()
    pdk = cr.resolve_pdk(pin)
    if not pdk.matches_pin and not args.allow_pdk_mismatch:
        raise cr.HarnessError(cr.pdk_mismatch_message(pdk, pin) + "\n  or re-run with --allow-pdk-mismatch")
    if args.probe:
        return run_probe(args, pdk, man)
    points = build_points(args.grid, man)
    git_info = cr.git_state()
    now = datetime.now(timezone.utc)
    record_id = f"{now:%Y%m%d}-{now:%H%M%S}-{git_info['sha']}-{args.grid}"
    run_dir = BUILD_DIR / record_id
    run_dir.mkdir(parents=True, exist_ok=True)
    head = sim_common.netlist_tb_head(TESTBENCH, run_dir / "tb", pdk)
    body = {d: build_body(head, d) for d in OFFSETS}
    request, files = build_request(points, body, pdk, "batch", args)
    print(f"experiment: {SLUG}  record: {record_id}  points: {len(points)}")
    if args.dry_run:
        for pt in points:
            print("  ", pt.point_id)
        print(files[f"units/{points[0].point_id}/deck.spice"][:1500])
        print("(dry run: nothing submitted)")
        return 0
    records_dir, snaps = HERE / "records", HERE / "netlist-snapshots"
    stage = evidence_store.stage_dir_for(SLUG, record_id)
    rec_md, rec_json, snap = records_dir / f"{record_id}.md", records_dir / f"{record_id}.json", snaps / f"{record_id}.spice"
    sim_common.refuse_existing((rec_md, rec_json, snap, stage, evidence_store.manifest_path(SLUG, record_id)))
    sub = run_dir / "batch"
    outcome = sim_common.submit_prepared(sub, None, request, f"{SLUG}: {len(points)} decks -> batch fleet", SLUG, files=files)
    report = json.loads((sub / "report.json").read_text() or "{}")
    units = sim_common.deck_units(report)
    if not units:
        raise cr.HarnessError(f"batch submit produced no usable deck report (exit {outcome['exit']}, status {outcome['status']}); "
                              f"NOT falling back to a local grid.\n  stderr: {(sub / 'klt.stderr').read_text().strip()[:1200]}")
    stage.mkdir(parents=True, exist_ok=True)
    results = []
    for pt in points:
        wave = unit_wave(sub / "out", pt.point_id)
        g = grade(pt, wave, 2e-3)
        u = units.get(pt.point_id)
        raw = sim_common.deck_streams(report, u) if u else "*** no unit returned"
        (stage / f"{pt.point_id}.log").write_text(files[f"units/{pt.point_id}/deck.spice"] + "\n----- ngspice output -----\n" + raw[-20000:])
        if wave:
            (stage / f"{pt.point_id}.wave.dat").write_text(wave)
        results.append({"point_id": pt.point_id, "process": pt.proc, "temperature_c": pt.temp_c, "rate_v_per_s": pt.rate,
                        "start": pt.start, "device": pt.device, "offset_mv": pt.offset_mv, "grade": g,
                        "solver": sim_common.log_solver(raw) if u else None})
        print(f"{pt.point_id:<40} {g['class']:<17} bias_ok={vv(g.get('bias_ok_up_v'))} por_up={vv(g.get('por_up_v'))} pulses={g.get('pulse_count')}")
    sim_common.snapshot_deck_request(sub, stage, run_dir, REPO_ROOT)
    art_manifest, art_summary = evidence_store.store_or_exit(SLUG, record_id, stage)
    snap.parent.mkdir(parents=True, exist_ok=True)
    snap.write_text("\n".join(f"* ===== derived netlist, offset device {d} =====\n{b}\n" for d, b in body.items()) + ".end\n")
    pdk_block, tools_block, batch_block = sim_common.deck_list_record_blocks(
        pdk, pin, report, points=results, capacity_wait_s=args.wait_for_capacity,
        attempts=sim_common.attempt_messages(sub, run_dir, REPO_ROOT))
    procs = sorted({p.proc for p in points})
    full = args.grid == "full"
    rec = {
        "record_id": record_id, "timestamp": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "author": args.author or cr.default_author(),
        "supersedes": args.supersedes, "grid": args.grid,
        "experiment": {"slug": SLUG, "title": man["title"], "claim": man["claim"], "provenance": "schematic",
                       "provenance_source": str(TESTBENCH.relative_to(REPO_ROOT)), "statistical_convention": man["statistical_convention"]},
        "pdk": pdk_block, "tools": tools_block, "pdk_line": f"{pdk.dir} (open_pdks {pdk.installed_commit})", "backend": "batch", "batch": batch_block,
        "git": git_info,
        "matrix": {"process": procs, "temperature_c": sorted({p.temp_c for p in points}), "rate_v_per_s": sorted({p.rate for p in points}),
                   "n_points": len(points), "is_subset": True,
                   "subset_reason": args.subset_reason or (
                       "full-grid record: the three paired corners ss/-40C, tt/27C, ff/125C rather than the 15-point process x temperature matrix; "
                       "the supply is the swept variable (0 -> 3.63 V), so there is no separate supply axis" if full else
                       "PILOT record at the single ss/-40C corner (where the mc14 pulse was seen) to bracket the pulse onset before the full grid; not a PVT claim")},
        "points": results, "verdict": verdict(results),
        "links": {"testbench": str(TESTBENCH.relative_to(REPO_ROOT)), "runner": str(Path(__file__).resolve().relative_to(REPO_ROOT)),
                  "netlist_snapshot": str(snap.relative_to(REPO_ROOT)), "artifact_manifest": str(art_manifest.relative_to(REPO_ROOT)),
                  "artifact_summary": str(art_summary.relative_to(REPO_ROOT))},
    }
    records_dir.mkdir(parents=True, exist_ok=True)
    rec_json.write_text(json.dumps(rec, indent=2, sort_keys=True, default=str) + "\n")
    rec_md.write_text(render_md(rec))
    print(f"record: {rec_md.relative_to(REPO_ROOT)}\nverdict: {rec['verdict']}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except cr.HarnessError as err:
        print(f"run_early_assert: error: {err}", file=sys.stderr)
        sys.exit(1)
