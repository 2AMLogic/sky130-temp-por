def tb_netlist_head(state: str, run_dir: Path, pdk) -> str:
    """xschem-netlist the state's testbench; keep only the testbench part (DUT comes from the committed export)."""
    sch = HERE / "testbench" / f"tb_temp_por_iq_{STATE_TAG[state]}.sch"
    produced = cr.netlist_with_xschem(sch, run_dir / "tb" / STATE_TAG[state], pdk)
    text = produced.read_text().replace(str(REPO_ROOT) + os.sep, "")
    head = text.split("\n* expanding")[0]
    return "\n".join(ln for ln in head.splitlines() if ln.strip().lower() != ".end") + "\n"


def instrumented_dut() -> str:
    dut = DUT_NETLIST.read_text()
    dut = "\n".join(ln for ln in dut.splitlines() if ln.strip().lower() != ".end") + "\n"
    for find, repl in INSTRUMENT:
        if dut.count(find) != 1:
            raise SystemExit(f"instrumentation target not found exactly once in {DUT_NETLIST.name}: {find!r}")
        dut = dut.replace(find, repl)
    return dut


def build_netlist(head: str, state: str, man: dict) -> str:
    m = man["measurement"]
    banner = (
        f"* {SLUG} ({state}): generated by sim/iq-top/run_iq_campaign.py -- do not edit\n"
        f"* DUT = design/netlist/temp_por_top.spice with 0 V ammeters in series with each sub-cell VDD pin (attribution only)\n"
        f".param rate={m['rate_v_per_s']:g}\n"
        "* ng_nomodcheck: same setting as sim/spiceinit; carried in the netlist because the\n"
        "* fleet runner ignores options.ngspice_init (see experiment.json ngspice_note)\n"
        ".control\nset ng_nomodcheck\n.endc\n"
    )
    return banner + head + "\n" + instrumented_dut()


def build_request(netlist_name: str, man: dict, backend: str, capacity_wait_s: float = 0) -> dict:
    m = man["measurement"]
    c = man["corners"]
    tw = m["trail_window_s"]
    req = {
        "netlist": netlist_name,
        "backend": backend,
        "models": {"pdk": "sky130A", "lib": MODEL_LIB},
        "corners": {"process": c["process"], "supply_v": {"vset": c["supply_v"]}, "temperature_c": c["temperature_c"]},
        "analysis": {"kind": "tran", "args": f"1u {m['tstop_s']:.9g} 0 {m['tmax_s']:.3g}"},
        "measurements": [
            {"name": "iq_trail_neg", "spice": f".meas tran iq_trail_neg AVG i(bvdd) FROM={tw[0]:.9g} TO={tw[1]:.9g}", "unit": "A"},
            {"name": "vdd_trail", "spice": f".meas tran vdd_trail AVG v(vdd) FROM={tw[0]:.9g} TO={tw[1]:.9g}", "unit": "V"},
            {"name": "resetn_trail", "spice": f".meas tran resetn_trail AVG v(resetn) FROM={tw[0]:.9g} TO={tw[1]:.9g}", "unit": "V"},
        ],
        "options": {"timeout_s": 3000, "keep_artifacts": True, "waveforms": True},
    }
    if backend == "batch":
        req["batch"] = {"runner_version_check": "warn"}
        if capacity_wait_s:
            req["batch"]["capacity_wait_s"] = capacity_wait_s
    return req


def klt_version() -> str:
    p = subprocess.run(["klt", "--version"], capture_output=True, text=True)
    return p.stdout.strip() or p.stderr.strip()


def cmd_run(args) -> int:
    man = load_manifest()
    pdk = cr.resolve_pdk(cr.load_pin())
    git_info = cr.git_state()
    now = datetime.now(timezone.utc)
    run_id = args.run_id or f"{now:%Y%m%d-%H%M%S}-{git_info['sha']}"
    run_dir = BUILD / run_id
    if args.retry_failed:
        if not run_dir.exists():
            raise SystemExit(f"{run_dir} does not exist")
    else:
        if run_dir.exists():
            raise SystemExit(f"{run_dir} exists; refusing to reuse a run id")
        run_dir.mkdir(parents=True)
    states = args.state or STATES
    rate = man["measurement"]["rate_v_per_s"]
    work = list(states)
    if args.retry_failed:
        work = [s for s in states if not sim_common.report_usable(run_dir / s / sim_common.rate_tag(rate) / "report.json")]
        say(f"retrying {len(work)} request(s) without a usable report, capacity_wait_s={args.capacity_wait}")
    heads = {s: tb_netlist_head(s, run_dir if not args.retry_failed else run_dir / "retry", pdk) for s in work}
    meta = {"run_id": run_id, "started_utc": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "states": states, "klt_client": klt_version(),
            "klt_sim_backend_env": os.environ.get("KLT_SIM_BACKEND"), "git": git_info}
    if not args.retry_failed:
        (run_dir / "run.json").write_text(json.dumps(meta, indent=2) + "\n")

    def one(state):
        req = build_request("netlist.spice", man, "batch", args.capacity_wait)
        return sim_common.submit_request(state, rate, run_dir, build_netlist(heads[state], state, man), req, "", len(grid(man)))

    results = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=min(2, args.jobs)) as ex:
        for f in [ex.submit(one, s) for s in work]:
            try:
                results.append(f.result())
            except Exception as err:  # noqa: BLE001 -- recorded, never swallowed
                results.append({"error": repr(err)})
                say(f"[error] submit raised: {err!r}")
    old = json.loads((run_dir / "run.json").read_text())
    if args.retry_failed:
        old.setdefault("retries", []).append({"at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "capacity_wait_s": args.capacity_wait, "results": results})
    else:
        old["submit_results"] = results
    (run_dir / "run.json").write_text(json.dumps(old, indent=2) + "\n")
    print(f"raw outputs: {run_dir}")
    return 0


def cmd_crosscheck(args) -> int:
    man = load_manifest()
    pdk = cr.resolve_pdk(cr.load_pin())
    run_dir = BUILD / args.run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    for state in args.state or STATES:
        d = run_dir / "crosscheck" / STATE_TAG[state]
        d.mkdir(parents=True, exist_ok=True)
        (d / "netlist.spice").write_text(build_netlist(tb_netlist_head(state, run_dir / "xc", pdk), state, man))
        req = build_request("netlist.spice", man, "local")
        req["corners"] = {"process": ["tt"], "supply_v": {"vset": [3.3]}, "temperature_c": [27]}
        req["options"]["ngspice_init"] = [ln.strip() for ln in (SIM_DIR / "spiceinit").read_text().splitlines() if ln.strip() and not ln.startswith("*")]
        (d / "request.json").write_text(json.dumps(req, indent=2) + "\n")
        say(f"[crosscheck] {state}: one local corner (tt/27C/3.30V) on local ngspice")
        p = subprocess.run(["klt", "sim", str(d / "request.json"), "--backend", "local", "-o", str(d / "out"), "--format", "json"], capture_output=True, text=True, timeout=3600)
        (d / "report.json").write_text(p.stdout)
        (d / "klt.stderr").write_text(p.stderr)
        say(f"[crosscheck] {state}: exit {p.returncode}")
    return 0


