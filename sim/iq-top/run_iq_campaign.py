#!/usr/bin/env python3
"""Driver for the assembled temp_por_top Iq campaign (issue #107).

The 45-point PVT grid, per state, is expressed as ONE ``klt sim`` corner
request per state (process x supply x temperature are klt's own corner axes)
and goes to the Spot batch fleet with an explicit ``--backend batch``; this
script never launches ngspice over the grid itself, and there is no local
fallback for the grid if the fleet refuses (the refusal is recorded).

Stages (each a subcommand):

  run         build the two generated decks + requests and submit them to the fleet.
  crosscheck  one single-corner (tt / 27 C / 3.30 V) LOCAL probe per state (``--backend local``).
  record      grade every retrieved waveform with iq_checker.py and write the append-only
              evidence (snapshots, scrubbed klt reports, decimated traces, md + json twins).
  selftest    run the settling/physicality checker on synthetic settled / drifting currents.

States: por-iq (RESETn forced low by a testbench source), iq-total (natural released
state); temp-iq is derived as iq-total - por-iq, labelled incremental.
"""

