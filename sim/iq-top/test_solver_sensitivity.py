#!/usr/bin/env python3
"""Unit tests for the iq-total solver-sensitivity harness (issue #160).

Stdlib only, no SPICE, no records written.  Proves: (1) solver-variant selection reaches the
generated deck (and only the options line changes; the control deck is byte-identical to the
original campaign's) and the request is variant-independent; (2) invalid / non-physical /
unsettled waveforms cannot become usable measurements; (3) the predeclared comparison criterion
and the exclusion classification rules behave as documented, including unknowns.

Run: python3 -I sim/iq-top/test_solver_sensitivity.py
"""

from __future__ import annotations

import copy
import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import iq_checker as qc  # noqa: E402
import run_iq_campaign as rc  # noqa: E402
import run_iq_sensitivity as rs  # noqa: E402

MAN = rc.sim_common.load_manifest(rc.MANIFEST)
SNAP = next((rc.HERE / "netlist-snapshots").glob("20261009-191705-df85523")) / "iq-total.netlist.spice"
TOL = rs.sens(MAN)["comparison_criterion"]["agreement_rel_tol"]


def original_head() -> str:
    """The testbench head of the original campaign's committed deck (everything before the DUT)."""
    text = SNAP.read_text()
    start = text.index("** sch_path: sim/iq-top/testbench")
    end = text.index("\n* temp_por_top -- generated by")
    return text[start:end] + "\n"


def pt(status, i=None, **kw):
    d = {"status": status}
    if i is not None:
        d["i_total_a"] = i
    d.update(kw)
    return d


class VariantSelection(unittest.TestCase):
    def test_manifest_declares_baseline_and_two_variants(self):
        self.assertEqual(rs.variant_names(MAN), ["baseline", "trtol7", "reltol2e-4"])
        self.assertIsNone(rs.sens(MAN)["variants"]["baseline"]["options"])

    def test_control_deck_is_byte_identical_to_original_build(self):
        head = original_head()
        self.assertEqual(rs.build_variant_netlist(head, "baseline", MAN), rc.build_netlist(head, rs.STATE, MAN))
        # and that original build reproduces the committed original deck (control really is the old deck)
        self.assertEqual(rs.build_variant_netlist(head, "baseline", MAN).split("\n", 2)[0], SNAP.read_text().split("\n", 1)[0])

    def test_variant_reaches_deck_and_only_the_options_line_changes(self):
        head = original_head()
        base = rs.build_variant_netlist(head, "baseline", MAN).splitlines()
        for name in ("trtol7", "reltol2e-4"):
            opts = rs.sens(MAN)["variants"][name]["options"]
            deck = rs.build_variant_netlist(head, name, MAN)
            self.assertEqual(deck.count(f".options {opts}"), 1)
            lines = deck.splitlines()
            self.assertEqual(len(lines), len(base))
            diff = [(a, b) for a, b in zip(base, lines) if a != b]
            self.assertEqual(diff, [(".options method=gear trtol=50", f".options {opts}")])

    def test_decks_differ_between_variants_and_request_does_not(self):
        head = original_head()
        decks = {n: rs.build_variant_netlist(head, n, MAN) for n in rs.variant_names(MAN)}
        self.assertEqual(len(set(decks.values())), 3)
        self.assertEqual(len({rs.sha256(d) for d in decks.values()}), 3)
        req = rs.build_variant_request(MAN)
        self.assertEqual(req, rc.build_request("netlist.spice", MAN, "batch"))
        self.assertEqual(req["backend"], "batch")  # the grid always goes to the fleet
        self.assertEqual(req["analysis"]["args"], "1u 0.03 0 1e-05")  # windows / analysis card unchanged
        self.assertEqual((len(req["corners"]["process"]), len(req["corners"]["supply_v"]["vset"]), len(req["corners"]["temperature_c"])), (5, 3, 3))

    def test_missing_or_ambiguous_options_line_is_refused_not_a_silent_noop(self):
        head = original_head()
        with self.assertRaises(SystemExit):
            rs.variant_head(head.replace(".options method=gear trtol=50", "* none"), "trtol7", MAN)
        with self.assertRaises(SystemExit):
            rs.variant_head(head + ".options method=gear trtol=50\n", "trtol7", MAN)
        with self.assertRaises(SystemExit):
            rs.variant_head(head, "nope", MAN)


class InvalidWaveforms(unittest.TestCase):
    """Invalid, non-physical and unsettled full-resolution waveforms never become usable."""

    def run_one(self, wave_mod):
        man = copy.deepcopy(MAN)
        man["corners"] = {"process": ["tt"], "temperature_c": [27.0], "supply_v": [3.3]}
        with tempfile.TemporaryDirectory() as td:
            d = Path(td) / "trtol7" / rs.STATE / rc.sim_common.rate_tag(man["measurement"]["rate_v_per_s"])
            d.mkdir(parents=True)
            wave = wave_mod(qc.synth(rs.STATE, 3.3))
            names = list(wave)
            (d / "w.json").write_text(json.dumps({"variables": [{"name": n} for n in names], "points": [[wave[n][i] for n in names] for i in range(len(wave["time"]))]}))
            (d / "report.json").write_text(json.dumps({"status": "ok", "corner_count": 1, "corners": [
                {"process": "tt", "temperature_c": 27.0, "supply_v": {"vset": 3.3}, "status": "ok", "measurements": [], "diagnostics": [], "artifacts": {"waveform": str(d / "w.json")}}]}))
            traces: dict = {}
            res = rs.analyze_variant("trtol7", Path(td), man, traces)
            return res["points"]["tt_27c_3.30v"], traces

    def test_good_waveform_is_usable(self):
        p, _ = self.run_one(lambda w: w)
        self.assertTrue(rs.usable(p))

    def test_nan_waveform_is_not_usable(self):
        def mod(w):
            w["i(bvdd)"][-5] = float("nan")
            return w
        p, tr = self.run_one(mod)
        self.assertFalse(rs.usable(p))
        self.assertTrue(p.get("invalid_input"))
        self.assertEqual(p["status"], "nonconverged")
        self.assertFalse(tr.get("trtol7"))

    def test_negative_current_is_nonphysical_and_not_usable(self):
        def mod(w):
            w["i(bvdd)"] = [-x if t > 0.02 else x for t, x in zip(w["time"], w["i(bvdd)"])]
            return w
        p, _ = self.run_one(mod)
        self.assertEqual(p["status"], "non-physical-branch")
        self.assertFalse(rs.usable(p))

    def test_drifting_current_is_unsettled_and_not_usable(self):
        p, _ = self.run_one(lambda w: qc.synth(rs.STATE, 3.3, drift=0.2))
        self.assertEqual(p["status"], "unsettled")
        self.assertFalse(rs.usable(p))

    def test_usable_rejects_ok_status_without_finite_positive_current(self):
        self.assertFalse(rs.usable(pt("ok", float("nan"))))
        self.assertFalse(rs.usable(pt("ok", -1e-6)))
        self.assertFalse(rs.usable(pt("ok", 1e-5, invalid_input=True)))
        self.assertFalse(rs.usable(None))
        self.assertTrue(rs.usable(pt("ok", 1e-5)))


class Comparison(unittest.TestCase):
    def test_agreement_threshold_is_the_predeclared_one_percent(self):
        self.assertEqual(TOL, 0.01)
        self.assertTrue(rs.agreement({"a": 20e-6, "b": 20.19e-6}, TOL)["agree"])
        self.assertFalse(rs.agreement({"a": 20e-6, "b": 20.3e-6}, TOL)["agree"])
        self.assertIsNone(rs.agreement({"a": 20e-6}, TOL)["agree"])

    def classes(self, **runs):
        return rs.classify_exclusion(runs, TOL)[0]

    def test_classification_rules(self):
        NP, U = pt("non-physical-branch", -1e-6), pt("unsettled", 2e-5)
        ok = lambda i: pt("ok", i)  # noqa: E731
        miss = pt("nonconverged", reason="no waveform")
        self.assertEqual(self.classes(baseline=NP, trtol7=NP, r=NP), "reproduced-non-physical")
        self.assertEqual(self.classes(baseline=U, trtol7=U, r=U), "physical-failure")
        self.assertEqual(self.classes(baseline=NP, trtol7=ok(2e-5), r=NP), "recovered-solver-sensitive")
        self.assertEqual(self.classes(baseline=ok(2e-5), trtol7=ok(2.01e-5), r=NP), "recovered-solver-sensitive")
        self.assertEqual(self.classes(baseline=ok(2e-5), trtol7=ok(2.5e-5), r=NP), "unresolved")  # physical disagreement preserved
        self.assertEqual(self.classes(baseline=NP, trtol7=NP, r=miss), "unresolved")  # missing run => unknown, not reproduced
        self.assertEqual(self.classes(baseline=NP, trtol7=NP, r=None), "unresolved")
        self.assertEqual(self.classes(baseline=NP, trtol7=U, r=NP), "unresolved")
        self.assertEqual(self.classes(baseline=NP, trtol7=ok(2e-5), r=miss), "recovered-solver-sensitive")
        # an invalid-input point never counts as a graded result or as ok
        self.assertEqual(self.classes(baseline=NP, trtol7=NP, r=pt("nonconverged", invalid_input=True)), "unresolved")

    def test_compare_accounts_for_all_45_points_and_flags_new_failures(self):
        pts = {rc.corner_id(*g): pt("ok", 20e-6) for g in rc.grid(MAN)}
        orig = copy.deepcopy(pts)
        orig["tt_27c_3.30v"] = pt("non-physical-branch", -1e-6)
        orig["ss_27c_3.30v"] = pt("non-physical-branch", -1e-6)
        per = {n: {"points": copy.deepcopy(pts)} for n in rs.variant_names(MAN)}
        per["trtol7"]["points"]["ff_27c_3.30v"] = pt("non-physical-branch", -1e-6)  # newly failing
        per["reltol2e-4"]["points"]["tt_-40c_3.30v"] = pt("ok", 21e-6)  # disagreement
        for n in per:
            del per[n]["points"]["ss_27c_3.30v"]  # fleet gave nothing for this one -> unknown
        out = rs.compare(per, orig, MAN)
        self.assertEqual(len(out["rows"]), 45)
        self.assertEqual(out["classes"]["ss_27c_3.30v"]["class"], "unresolved")
        self.assertEqual(out["classes"]["tt_27c_3.30v"]["class"], "recovered-solver-sensitive")
        self.assertEqual([x["id"] for x in out["newly_failing"]].count("ff_27c_3.30v"), 1)
        self.assertIn("tt_-40c_3.30v", out["summary"]["corners_disagree"])
        for n in rs.variant_names(MAN):
            self.assertEqual(sum(out["summary"]["per_variant_counts"][n].values()), 45)
        self.assertEqual(out["summary"]["per_variant_counts"]["baseline"]["no-result"], 1)


if __name__ == "__main__":
    unittest.main()
